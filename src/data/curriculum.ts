function makePack(seed: Seed, p: Pack, index: number): LessonContext {
  const [en, ru, word, translation, ipa, part, blank, answer, error] = p;
  const id = contexts[index].id;
  const hints = [seed.rule, seed.formula, `Начните с: ${en.split(' ').slice(0, 2).join(' ')}…`];
  const common = { hints, explanation: `${en} — ${ru} ${seed.rule}` };
  const tokens = en.replace(/[?.!,]/g, '').split(' ');
  const alternatives = [en];
  if (en.includes('does not')) alternatives.push(en.replace('does not', "doesn't"));
  if (en.includes('do not')) alternatives.push(en.replace('do not', "don't"));
  if (en.includes(' every ')) alternatives.push(en.replace(' every ', ' each '));
  if (en.includes('films')) alternatives.push(en.replace('films', 'movies'));
  if (en.includes('now')) alternatives.push(en.replace('now', 'right now'));
  if (en.startsWith('Can I have'))
    alternatives.push(
      en.replace('Can I have', 'Could I have'),
      en.replace('Can I have', 'May I have'),
    );
  if (en === 'She has an office.') alternatives.push('She has got an office.');
  if (en === 'I have a ticket.') alternatives.push('I have got a ticket.');
  if (en === 'I have a dog.') alternatives.push('I have got a dog.');
  if (en === 'There is a hotel nearby.') alternatives.push('There is a hotel near here.');
  if (en === 'There is a park nearby.') alternatives.push('There is a park near here.');
  if (en === 'I cooked dinner yesterday.')
    alternatives.push('I made dinner yesterday.', 'Yesterday I cooked dinner.');
  if (en === 'She is writing an email now.') alternatives.push('She is writing an email.');
  if (en === 'We are waiting for the train.') alternatives.push('We are waiting for a train.');
  if (en === 'She has finished the report.') alternatives.push('She finished the report.');
  if (en === 'I have seen this film.')
    alternatives.push('I have seen this movie.', 'I saw this film.', 'I saw this movie.');
  if (en === 'We have visited London.') alternatives.push('We have been to London.');
  if (en === 'She has read this novel.') alternatives.push('She read this novel.');
  if (en === 'He has made breakfast.') alternatives.push('He made breakfast.');
  return {
    id,
    examples: [
      { en, ru },
      { en: en, ru: `Обратите внимание: ${seed.formula}. ${ru}` },
    ],
    words: [
      {
        id: `${seed.id}-${id}-${word}`,
        en: word,
        ru: translation,
        ipa,
        part,
        level: seed.level,
        topic: id,
        example: en,
        translation: ru,
      },
    ],
    exercises: [
      {
        id: `${seed.id}-${id}-word`,
        type: 'en-ru',
        prompt: `Переведите слово: ${word}`,
        answers: [translation, ...(word === 'like' ? ['любить'] : [])],
        skill: 'Vocabulary',
        ...common,
        hints: [`Часть речи: ${part}`, `Контекст: ${ru}`, `Первая буква: ${translation[0]}`],
      },
      {
        id: `${seed.id}-${id}-reverse`,
        type: 'ru-en',
        prompt: `Напишите по-английски: ${translation}`,
        answers: [word],
        skill: 'Vocabulary',
        ...common,
        hints: [
          `Часть речи: ${part}`,
          `В слове ${word.length} букв`,
          `Начало: ${word.slice(0, Math.max(1, Math.floor(word.length / 2)))}…`,
        ],
      },
      {
        id: `${seed.id}-${id}-blank`,
        type: 'blank',
        prompt: `${blank} (${ru})`,
        answers: [answer],
        skill: 'Grammar',
        ...common,
        hints: [seed.rule, seed.formula, `Ответ начинается с ${answer[0]}`],
      },
      {
        id: `${seed.id}-${id}-choice`,
        type: 'choice',
        prompt: 'Выберите корректное предложение.',
        answers: [en],
        options: index % 2 === 0 ? [error, en] : [en, error],
        skill: 'Grammar',
        ...common,
      },
      {
        id: `${seed.id}-${id}-order`,
        type: 'order',
        prompt: `Соберите предложение: ${ru}`,
        answers: [en],
        tokens: [...tokens.slice(2), ...tokens.slice(0, 2)].reverse(),
        skill: 'Writing',
        ...common,
      },
      {
        id: `${seed.id}-${id}-translation`,
        type: 'translation',
        prompt: `Переведите: ${ru}`,
        answers: alternatives,
        skill: 'Writing',
        ...common,
      },
      {
        id: `${seed.id}-${id}-dictation`,
        type: 'dictation',
        prompt: 'Прослушайте и запишите предложение.',
        audio: en,
        answers: [en],
        skill: 'Listening',
        ...common,
      },
      {
        id: `${seed.id}-${id}-mistake`,
        type: 'mistake',
        prompt: `Исправьте предложение: ${error}`,
        answers: [en],
        skill: 'Grammar',
        ...common,
      },
    ],
  };
}
